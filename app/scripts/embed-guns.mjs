// Embeds the generic gun GLBs (../assets/guns: detailed, ../assets/guns-simple: M5.5 level) into src/gun-data.ts for the
// labs (2026-11-06). The game's own guns stay in combat-data.ts (scripts/embed-combat.mjs).
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),assets=path.resolve(root,'../assets');
// Which hold each gun uses (combat-motion.ts WeaponClass): one-handed pistols, or two hands on a long gun.
const CLASS={revolver:'pistol',tranq_pistol:'pistol',machine_pistol:'pistol',compact_smg:'long',shotgun:'long',shotgun_short:'long',sniper_rifle:'long',hunting_rifle:'long'};
const list=[],models={};
for(const [set,dir,name] of [['hd','guns','作り込み'],['simple','guns-simple','簡易']]){
 for(const e of JSON.parse(await readFile(path.join(assets,dir,'build-info.json'),'utf8'))){
  const id=`${set}:${e.id}`;list.push({id,label:`${e.label}（${name}）`,cls:CLASS[e.id]??'long',moving:Object.keys(e.moving??{})});
  models[id]=(await readFile(path.join(assets,dir,'models',e.id,e.id+'.glb'))).toString('base64');}}
let out='// Generated by scripts/embed-guns.mjs — do not edit by hand.\n';
out+="export type GunInfo={id:string;label:string;cls:'pistol'|'long';moving:string[]};\n";
out+='export const GUN_LIST:GunInfo[]='+JSON.stringify(list)+';\nexport const GUN_MODELS:Record<string,string>={\n';
for(const [id,b] of Object.entries(models))out+=` ${JSON.stringify(id)}:'${b}',\n`;
await writeFile(path.join(root,'src/gun-data.ts'),out+'};\n');console.log('embedded',list.length,'guns');
