// Embeds the hand-held item GLBs from ../assets/items/models into src/item-data.ts (2026-11-05; single-file builds need
// no fetch). Rebuild the models with: blender -b -P ../assets/items/source/build_items.py
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),src=path.resolve(root,'../assets/items');
const info=JSON.parse(await readFile(path.join(src,'build-info.json'),'utf8'));
let out='// Generated by scripts/embed-items.mjs — do not edit by hand.\n';
out+='export type ItemInfo={id:string;kind:\'tool\'|\'melee\'|\'throw\';label:string;triangles:number;size_m:number[];anchors:Record<string,number[]>};\n';
out+='export const ITEM_INFO:ItemInfo[]='+JSON.stringify(info.map(({bytes,...e})=>e))+';\n';
out+='export const ITEM_MODELS:Record<string,string>={\n';
// Items made on their own (2026-11-06): the briefcase with its opening lid (assets/briefcase) replaces the simple one.
const own={briefcase:path.resolve(root,'../assets/briefcase/models/briefcase/briefcase.glb')};
for(const e of info){const b=await readFile(own[e.id]??path.join(src,'models',e.id,e.id+'.glb'));out+=` ${JSON.stringify(e.id)}:'${b.toString('base64')}',\n`;}
await writeFile(path.join(root,'src/item-data.ts'),out+'};\n');console.log('embedded',info.map(e=>e.id).join(', '));
