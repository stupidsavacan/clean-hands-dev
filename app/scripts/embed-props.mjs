// Embeds the gesture props from ../assets/props/models into src/prop-data.ts (2026-11-05). Rebuild the models with:
// blender -b -P ../assets/props/source/build_props.py
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),src=path.resolve(root,'../assets/props');
const info=JSON.parse(await readFile(path.join(src,'build-info.json'),'utf8'));
let out='// Generated by scripts/embed-props.mjs — do not edit by hand.\n';
out+='export type PropInfo={id:string;kind:\'hand\'|\'furniture\';label:string;triangles:number;size_m:number[];anchors:Record<string,number[]>};\n';
out+='export const PROP_INFO:PropInfo[]='+JSON.stringify(info.map(({bytes,...e})=>e))+';\n';
out+='export const PROP_MODELS:Record<string,string>={\n';
for(const e of info){const b=await readFile(path.join(src,'models',e.id,e.id+'.glb'));out+=` ${JSON.stringify(e.id)}:'${b.toString('base64')}',\n`;}
await writeFile(path.join(root,'src/prop-data.ts'),out+'};\n');console.log('embedded',info.map(e=>e.id).join(', '));
