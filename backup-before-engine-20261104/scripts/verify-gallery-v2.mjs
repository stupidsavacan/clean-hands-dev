 const r=await page.goto(base);check('Main URL HTTP 200',r.status()===200);
 const combat=await (await page.locator('#combat').elementHandle()).contentFrame();
 await combat.waitForFunction(()=>window.__combat?.ready(),null,{timeout:30000});
 await combat.locator('[data-who="bodyguard"]').click();
 await combat.waitForFunction(()=>document.querySelector('#qa')?.textContent?.includes('bodyguard'));
 await page.screenshot({path:'C:/Users/gamit/Downloads/CLEAN_HANDS_motion_gallery_bodyguard_preview.png'});
 check('Bodyguard selected',await combat.locator('#qa').textContent().then(x=>x.includes('bodyguard')));
