 await page.locator('[data-tab="daily"]').click();
 const daily=await (await page.locator('#daily').elementHandle()).contentFrame();
 await daily.locator('[data-kind="frisk"]').click();
 await daily.waitForTimeout(1800);
 check('M4 frisk UI active',await daily.locator('[data-kind="frisk"]').evaluate(e=>e.classList.contains('active')));
 check('M4 page loaded',await daily.locator('#loading').textContent().then(x=>!x));
 await page.screenshot({path:'C:/Users/gamit/Downloads/CLEAN_HANDS_motion_gallery_frisk_preview.png'});
 await page.locator('[data-tab="models"]').click();
 const models=await (await page.locator('#models').elementHandle()).contentFrame();
 await models.waitForFunction(()=>window.__modelGallery?.count===246,null,{timeout:30000});
 check('All GLBs in catalogue',await models.locator('#total').textContent().then(s=>s.includes('246')));
 await models.evaluate(()=>window.__modelGallery.loadByName('response'));
 await models.waitForFunction(()=>window.__modelGallery.selected()==='response',null,{timeout:30000});
