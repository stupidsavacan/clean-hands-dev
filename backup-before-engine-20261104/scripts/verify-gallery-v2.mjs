 await combat.locator('[data-who="agent"]').click();
 await combat.locator('[data-kind="crouchFire"]').click();
 await combat.waitForTimeout(250);
 check('Crouch fire active',await combat.locator('[data-kind="crouchFire"]').evaluate(e=>e.classList.contains('active')));
 check('Crouch fire live pose',await combat.locator('#qa').textContent().then(x=>x.includes('crouchFire')));
