import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {Director} from './app/src/ai.ts';
import {CollisionWorld} from './app/src/world.ts';
import {NavGrid} from './app/src/nav.ts';
import {sightBoxes} from './app/src/sight.ts';
import {MissionEvents} from './app/src/events.ts';
import {M3System} from './app/src/m3.ts';
import {DetectionSystem} from './app/src/detection.ts';
import {judgeKill} from './app/src/kills.ts';
const json=name=>JSON.parse(readFileSync(new URL(`./app/src/data/${name}.json`,import.meta.url),'utf8'));
const hotel=json('hotel'),rules=json('rules'),data=json('detection');
const world=new CollisionWorld(hotel),director=new Director(hotel,world,new NavGrid(world),sightBoxes(hotel),rules);
for(const n of director.npcs)n.life='unconscious';
const events=new MissionEvents(),m3=new M3System(director,hotel.hides,rules.m3);
const detection=new DetectionSystem(director,events,m3.hotel,hotel.cameras,data,hotel);
const camera=hotel.cameras.find(c=>c.id==='CAM_lobby');
const player={x:camera.x+Math.sin(camera.heading)*6,y:0,z:camera.z+Math.cos(camera.heading)*6,floor:0,speed:0,running:false,crouched:false,tampering:false,disguise:'suit'};
assert.equal(detection.sees(camera,player),true);
const hit=detection.shotAt({x:player.x,y:1.4,z:player.z},{x:camera.x-(player.x-camera.x)*.2,y:camera.y+.2,z:camera.z-(player.z-camera.z)*.2},1);
assert.equal(hit?.id,camera.id);
const killed=judgeKill(director,player,hotel.cameras);
assert.equal(detection.sees(camera,player),false);
assert.ok(killed.cameras.includes(camera.id));
console.log(JSON.stringify({case:'destroyed-camera-judgement',recordingSees:detection.sees(camera,player),killJudgement:killed},null,2));
const recorderPlayer={...player,x:data.recorder.x,z:data.recorder.z};
detection.recorded=true;detection.beginRecorder(false);
for(let t=0;t<data.recorder.breakSeconds+.2;t+=.1)detection.step(.1,recorderPlayer,{illegal:false,trespass:false,carrying:false},t,false,true);
assert.equal(detection.recorded,false);
const workingCamera=hotel.cameras.find(c=>c.id==='CAM_lobby');
// A second system isolates recorder destruction from the individual-camera destruction case.
const second=new DetectionSystem(director,events,m3.hotel,hotel.cameras,data,hotel);
second.recorded=true;second.beginRecorder(false);
for(let t=0;t<data.recorder.breakSeconds+.2;t+=.1)second.step(.1,recorderPlayer,{illegal:false,trespass:false,carrying:false},t,false,true);
const afterBreak=second.recorded;
second.step(.3,player,{illegal:true,trespass:false,carrying:false},10,false,false);
assert.equal(afterBreak,false);assert.equal(second.recorded,true);
console.log(JSON.stringify({case:'recorder-break-then-new-recording',afterBreak,afterIllegalAct:second.recorded,cameraStillWorking:second.sees(workingCamera,player)},null,2));
